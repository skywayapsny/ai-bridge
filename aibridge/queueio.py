"""Shared file-queue protocol for ai-bridge.

Single source of truth for the on-disk queue layout used by bridge.py,
worker.py, poll.py and agent.py:

    queue/req_<id>.json      — pending OpenAI-compatible request
    queue/claimed_<id>.json  — request parked while an agent holds a lease
    queue/claim_<id>.json    — lease record {client_id, lease_token, expires_at}
    queue/resp_<id>.json     — agent/worker response for that request id

Claiming writes a claim record and moves req_ -> claimed_ under a queue lock;
when the lease expires the request returns to the queue automatically
(restored lazily by restore_expired_claims()).

Writers always publish via a temporary file + atomic rename, so readers
never observe a partially written JSON document.
"""
from __future__ import annotations

import fcntl
import json
import os
import re
import tempfile
import time
import uuid
from contextlib import contextmanager
from pathlib import Path

_PACKAGE_PARENT = Path(__file__).resolve().parent.parent
_DEFAULT_QUEUE = (_PACKAGE_PARENT if (_PACKAGE_PARENT / "bridge.py").is_file()
                  else Path.cwd()) / "queue"
QUEUE_DIR = Path(os.getenv("AI_BRIDGE_QUEUE_DIR", _DEFAULT_QUEUE)).resolve()

REQ_PREFIX = "req_"
CLAIMED_PREFIX = "claimed_"
CLAIM_PREFIX = "claim_"
RESP_PREFIX = "resp_"
JSON_SUFFIX = ".json"

DEFAULT_LEASE_SECONDS = 300.0

# Request ids are generated by the bridge (uuid hex), but responders receive
# them over HTTP and must not be able to escape QUEUE_DIR via path traversal.
REQ_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$")


def is_valid_req_id(req_id: str) -> bool:
    return bool(REQ_ID_RE.fullmatch(req_id))


def req_path(req_id: str) -> Path:
    return QUEUE_DIR / f"{REQ_PREFIX}{req_id}{JSON_SUFFIX}"


def claimed_path(req_id: str) -> Path:
    return QUEUE_DIR / f"{CLAIMED_PREFIX}{req_id}{JSON_SUFFIX}"


def claim_path(req_id: str) -> Path:
    return QUEUE_DIR / f"{CLAIM_PREFIX}{req_id}{JSON_SUFFIX}"


def resp_path(req_id: str) -> Path:
    return QUEUE_DIR / f"{RESP_PREFIX}{req_id}{JSON_SUFFIX}"


def read_json(path: Path) -> dict:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError("Expected a JSON object")
    return value


def load_json(path: Path) -> dict | None:
    """read_json that tolerates missing/corrupt files."""
    try:
        return read_json(path)
    except (OSError, ValueError):
        return None


def write_json_atomic(path: Path, payload: dict) -> None:
    """Write JSON via tmp file + rename so readers never see a partial file."""
    path.parent.mkdir(parents=True, mode=0o700, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=path.name, suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, ensure_ascii=False, indent=2)
        os.replace(tmp_name, path)
    except BaseException:
        Path(tmp_name).unlink(missing_ok=True)
        raise


def write_request(req_id: str, payload: dict) -> Path:
    path = req_path(req_id)
    write_json_atomic(path, payload)
    return path


def write_response(req_id: str, payload: dict) -> Path:
    path = resp_path(req_id)
    write_json_atomic(path, payload)
    return path


# ─── Claim / lease ────────────────────────────────────────────────────────────


class QueueConflict(Exception):
    def __init__(self, status: int, detail: str):
        super().__init__(detail)
        self.status = status


@contextmanager
def _queue_lock():
    # A stable inode coordinates independent server, worker and poll processes.
    # The kernel releases the lock when the owner exits, even after a crash.
    QUEUE_DIR.mkdir(parents=True, mode=0o700, exist_ok=True)
    fd = os.open(QUEUE_DIR / ".queue.lock", os.O_CREAT | os.O_RDWR, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX)
        yield
    finally:
        os.close(fd)


def claim(req_id: str, client_id: str, lease_seconds: float = DEFAULT_LEASE_SECONDS) -> dict | None:
    """Lease one pending request and publish its token atomically."""
    with _queue_lock():
        req = req_path(req_id)
        if not req.is_file() or claim_path(req_id).exists() or resp_path(req_id).exists():
            return None
        request = load_json(req)
        if request is None or _request_timed_out(request):
            return None
        record = {
            "request_id": req_id,
            "client_id": client_id,
            "lease_token": uuid.uuid4().hex,
            "expires_at": time.time() + lease_seconds,
        }
        write_json_atomic(claim_path(req_id), record)
        try:
            os.replace(req, claimed_path(req_id))
        except OSError:
            claim_path(req_id).unlink(missing_ok=True)
            raise
        return record


def load_claim(req_id: str) -> dict | None:
    return load_json(claim_path(req_id))


def _request_timed_out(payload: dict) -> bool:
    deadline = payload.get("deadline_at")
    return isinstance(deadline, (int, float)) and deadline <= time.time()


def _expiry(record: dict) -> float:
    try:
        return float(record.get("expires_at", 0))
    except (TypeError, ValueError):
        return 0.0


def verify_lease(req_id: str, lease_token: str) -> bool:
    record = load_claim(req_id)
    return (record is not None and record.get("lease_token") == lease_token
            and _expiry(record) > time.time())


def _check_lease(record: dict | None, lease_token: str) -> None:
    if record is None:
        raise QueueConflict(404, "claim not found")
    if record.get("lease_token") != lease_token:
        raise QueueConflict(403, "invalid lease token")
    if not _expiry(record) > time.time():
        raise QueueConflict(409, "lease already expired")


def renew_claim(req_id: str, lease_seconds: float = DEFAULT_LEASE_SECONDS,
                *, lease_token: str | None = None) -> float | None:
    with _queue_lock():
        record = load_claim(req_id)
        if lease_token is not None:
            _check_lease(record, lease_token)
        if record is None:
            return None
        record["expires_at"] = time.time() + lease_seconds
        write_json_atomic(claim_path(req_id), record)
        return record["expires_at"]


def _return_to_pending(req_id: str) -> None:
    claimed = claimed_path(req_id)
    req = req_path(req_id)
    if claimed.exists() and not req.exists():
        os.replace(claimed, req)
    claim_path(req_id).unlink(missing_ok=True)


def release_claim(req_id: str, *, lease_token: str | None = None) -> None:
    with _queue_lock():
        if lease_token is not None:
            _check_lease(load_claim(req_id), lease_token)
        _return_to_pending(req_id)


def _finish_claim(req_id: str) -> None:
    if resp_path(req_id).exists():
        # The pending filename is also the waiter’s marker. Keep it until
        # the HTTP client consumes the response. A response blocks new claims.
        _return_to_pending(req_id)
    else:
        claim_path(req_id).unlink(missing_ok=True)
        claimed_path(req_id).unlink(missing_ok=True)


def finish_claim(req_id: str) -> None:
    with _queue_lock():
        _finish_claim(req_id)


def complete_request(req_id: str, payload: dict, *, lease_token: str | None = None,
                     require_claim: bool = False, local_override: bool = False) -> dict | None:
    """Validate ownership and publish one response in the same transaction."""
    with _queue_lock():
        if resp_path(req_id).exists():
            raise QueueConflict(409, "request already answered")
        if not req_path(req_id).exists() and not claimed_path(req_id).exists():
            raise QueueConflict(404, "request not found")
        record = load_claim(req_id)
        if lease_token is not None:
            _check_lease(record, lease_token)
        elif not local_override:
            if record is not None:
                raise QueueConflict(403, "lease token is required")
            if require_claim or claimed_path(req_id).exists():
                raise QueueConflict(409, "request must be claimed first")
        write_response(req_id, payload)
        _finish_claim(req_id)
        return record


def restore_expired_claims() -> int:
    """Return expired requests to pending and preserve any published answer."""
    with _queue_lock():
        now = time.time()
        restored = 0
        for f in QUEUE_DIR.glob(f"{CLAIM_PREFIX}*{JSON_SUFFIX}"):
            req_id = f.stem.removeprefix(CLAIM_PREFIX)
            if resp_path(req_id).exists():
                _finish_claim(req_id)
                continue
            record = load_json(f)
            if record is not None and _expiry(record) > now:
                continue
            _return_to_pending(req_id)
            restored += 1
        return restored


# ─── Listing / inspection ────────────────────────────────────────────────────


def first_user_message(messages: list[dict], limit: int = 120) -> str:
    """Preview of the first user message — for listings and logs."""
    for m in messages:
        if m.get("role") != "user":
            continue
        content = m.get("content", "")
        if isinstance(content, str):
            return content[:limit]
        if isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and block.get("type") == "text":
                    return str(block.get("text", ""))[:limit]
    return ""


def iter_request_files() -> list[Path]:
    """All pending req_*.json files, oldest first.

    Race-safe: files deleted between glob and stat (cleanup_pair) are
    simply skipped instead of blowing up the caller.
    """
    items: list[tuple[float, Path]] = []
    for f in QUEUE_DIR.glob(f"{REQ_PREFIX}*{JSON_SUFFIX}"):
        try:
            items.append((f.stat().st_mtime, f))
        except OSError:
            continue
    return [f for _, f in sorted(items, key=lambda item: item[0])]


def list_pending() -> list[dict]:
    """Unanswered, unclaimed requests, oldest first, with summaries."""
    pending = []
    for f in iter_request_files():
        req_id = f.stem.removeprefix(REQ_PREFIX)
        if resp_path(req_id).exists() or claim_path(req_id).exists():
            continue
        data = load_json(f)
        if data is not None and _request_timed_out(data):
            continue
        if data is None:
            pending.append({"id": req_id, "error": "corrupted"})
            continue
        pending.append({
            "id": req_id,
            "model": data.get("model", "?"),
            "created_at": data.get("created_at", "?"),
            "messages_count": len(data.get("messages", [])),
            "tools_count": len(data.get("tools") or []),
            "first_user_msg": first_user_message(data.get("messages", [])),
        })
    return pending


def known_models() -> list[str]:
    """Model-теги, реально виденные в очереди (pending + claimed).

    Нужны /v1/models: проект должен увидеть те же id, что кладёт в
    запросы (devin-local, devin-code, brain-bridge и т.п.).
    """
    tags: set[str] = set()
    for prefix in (REQ_PREFIX, CLAIMED_PREFIX):
        for f in QUEUE_DIR.glob(f"{prefix}*{JSON_SUFFIX}"):
            data = load_json(f)
            if data is None:
                continue
            tag = data.get("model")
            if isinstance(tag, str) and tag:
                tags.add(tag)
    return sorted(tags)


def next_pending(model: str | None = None) -> tuple[str, dict] | None:
    """Oldest unanswered, unclaimed request as (req_id, payload), or None.

    `model` enables consumer isolation: only requests
    parked with the same model tag are eligible.
    """
    for f in iter_request_files():
        req_id = f.stem.removeprefix(REQ_PREFIX)
        if resp_path(req_id).exists() or claim_path(req_id).exists():
            continue
        data = load_json(f)
        if data is None or _request_timed_out(data):
            continue
        if model is not None and data.get("model") != model:
            continue
        return req_id, data
    return None


def sweep_orphans() -> int:
    """Drop/requeue queue artefacts that lost their owner.

    - resp without req AND without claimed → orphan resp (client timed out)
    - claimed without a claim file → move back to req_
    """
    with _queue_lock():
        removed = 0
        for f in QUEUE_DIR.glob(f"{RESP_PREFIX}*{JSON_SUFFIX}"):
            req_id = f.stem.removeprefix(RESP_PREFIX)
            if not req_path(req_id).exists() and not claimed_path(req_id).exists():
                f.unlink(missing_ok=True)
                removed += 1
        for f in QUEUE_DIR.glob(f"{CLAIMED_PREFIX}*{JSON_SUFFIX}"):
            req_id = f.stem.removeprefix(CLAIMED_PREFIX)
            if not claim_path(req_id).exists():
                _return_to_pending(req_id)
                removed += 1
        return removed


def sweep_timed_out_requests() -> int:
    """Remove expired HTTP queue artefacts left behind by a stopped server."""
    with _queue_lock():
        ids = set()
        for prefix in (REQ_PREFIX, CLAIMED_PREFIX):
            for path in QUEUE_DIR.glob(f"{prefix}*{JSON_SUFFIX}"):
                data = load_json(path)
                if data is not None and _request_timed_out(data):
                    ids.add(path.stem.removeprefix(prefix))
        for req_id in ids:
            _cleanup_pair(req_id)
        return len(ids)


def request_exists(req_id: str) -> bool:
    pending, claimed = req_path(req_id), claimed_path(req_id)
    if pending.exists() or claimed.exists():
        return True
    # A concurrent rename can make each probe miss. Recheck under the lock.
    with _queue_lock():
        return pending.exists() or claimed.exists()


def cleanup_pair(req_id: str) -> bool:
    """Remove all queue files for a request under the transition lock."""
    with _queue_lock():
        return _cleanup_pair(req_id)


def _cleanup_pair(req_id: str) -> bool:
    removed = False
    for path in (req_path(req_id), claimed_path(req_id), claim_path(req_id), resp_path(req_id)):
        try:
            path.unlink()
        except FileNotFoundError:
            continue
        removed = True
    return removed


# ─── Per-client stats (persistent) ───────────────────────────────────────────
#
# HTTP /brain/claim responders are counted in-memory by brain.BrainStats, but
# file-claim workers (worker.py) bypass that path. These counters live on disk
# so `GET /brain/stats` shows the whole fleet, not only HTTP claimers.

def bump_client_stat(client_id: str, key: str) -> None:
    """Increment a per-client counter (claims/answers). Best-effort: stats
    must never break the queue path."""
    try:
        with _queue_lock():
            path = QUEUE_DIR / "stats_clients.json"
            data = load_json(path) or {}
            by_client = data.setdefault("by_client", {})
            entry = by_client.setdefault(str(client_id), {"claims": 0, "answers": 0})
            entry[key] = int(entry.get(key, 0)) + 1
            write_json_atomic(path, data)
    except Exception:  # noqa: BLE001 — статистика не роняет очередь
        pass


def client_stats() -> dict:
    """Persistent by_client counters from file-claim workers."""
    data = load_json(QUEUE_DIR / "stats_clients.json") or {}
    by_client = data.get("by_client")
    return dict(by_client) if isinstance(by_client, dict) else {}


def stats() -> dict:
    reqs = list(QUEUE_DIR.glob(f"{REQ_PREFIX}*{JSON_SUFFIX}"))
    claimed = list(QUEUE_DIR.glob(f"{CLAIMED_PREFIX}*{JSON_SUFFIX}"))
    resps = list(QUEUE_DIR.glob(f"{RESP_PREFIX}*{JSON_SUFFIX}"))
    claims = list(QUEUE_DIR.glob(f"{CLAIM_PREFIX}*{JSON_SUFFIX}"))
    pending = [r for r in reqs
               if not resp_path(r.stem.removeprefix(REQ_PREFIX)).exists()]
    return {
        "total_requests": len(reqs),
        "total_responses": len(resps),
        "claimed": len(claimed),
        "claims": len(claims),
        "pending": len(pending),
        "queue_dir": str(QUEUE_DIR),
    }
